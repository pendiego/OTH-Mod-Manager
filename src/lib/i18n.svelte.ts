/** Traduz mensagens de erro do backend (escritas em português). */
export function tr(e: unknown): string {
  const msg = String(e);
  return i18n.lang === "en" ? ERR_EN.reduce((m, [p, en]) => m.replace(p, en), msg) : msg;
}
